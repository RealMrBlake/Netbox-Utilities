def max_sockets(name, family_max):
    """EPYC "P" models (e.g. 7402P, 9354P, 4484PX) are single-socket only."""
    if name.startswith("EPYC") and name.endswith(("P", "PX")):
        return 1
    return family_max


def entries():
    """Yield one dict per CPU, ready for CPUModel(**entry)."""
    for manufacturer, family, socket, year, family_max, models in FAMILIES:
        for name, cores, threads, base, boost, tdp in models:
            yield {
                "manufacturer": manufacturer,
                "family": family,
                "name": name,
                "cores": cores,
                "threads": threads,
                "base_clock_ghz": base,
                "boost_clock_ghz": boost,
                "tdp_watts": tdp,
                "socket": socket,
                "launch_year": year,
                "max_sockets": max_sockets(name, family_max),
            }


def sync(model, force=False):
    """Create missing catalogue CPUs; update untouched built-in ones. Returns (created, updated).

    ``model`` is the CPUModel class (also the historical one inside migrations).
    Entries with ``builtin=False`` were added by users and are never touched; built-in
    entries edited in the UI keep their values unless ``force`` is set.
    """
    from decimal import Decimal

    created = updated = 0
    existing = {(cpu.manufacturer, cpu.name.casefold()): cpu for cpu in model.objects.all()}
    for entry in entries():
        values = {
            **entry,
            "base_clock_ghz": Decimal(str(entry["base_clock_ghz"])),
            "boost_clock_ghz": Decimal(str(entry["boost_clock_ghz"])) if entry["boost_clock_ghz"] else None,
        }
        cpu = existing.get((entry["manufacturer"], entry["name"].casefold()))
        if cpu is None:
            model.objects.create(builtin=True, **values)
            created += 1
        elif cpu.builtin and (force or not cpu.customized):
            changed = [name for name, value in values.items() if getattr(cpu, name) != value]
            if changed:
                for name in changed:
                    setattr(cpu, name, values[name])
                cpu.save(update_fields=changed)
                updated += 1
    return created, updated
